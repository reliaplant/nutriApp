const STORAGE_KEY = 'refeit:lang';

export function getLang(): Lang {
  if (typeof window === 'undefined') return DEFAULT_LANG;
  const stored = window.localStorage.getItem(STORAGE_KEY) as Lang | null;
  return stored && (stored === 'es' || stored === 'pt') ? stored : DEFAULT_LANG;
}

export function setLang(lang: Lang) {
  if (typeof window === 'undefined') return;
  window.localStorage.setItem(STORAGE_KEY, lang);
  document.cookie = `refeit_lang=${lang}; path=/; max-age=31536000; samesite=lax`;
  document.documentElement.lang = lang;
  window.dispatchEvent(new CustomEvent('refeit:lang-change', { detail: lang }));
}

/**
 * Traduce una clave anidada con notación de punto. Ej: t('login.title')
 * Si el valor es array u objeto, lo devuelve tal cual.
 */
export function t(key: string, lang?: Lang): any {
  const activeLang = lang || (typeof window === 'undefined' ? DEFAULT_LANG : getLang());
  const dict: any = (translations as any)[activeLang] || translations.es;
  const parts = key.split('.');
  let cur: any = dict;
  for (const p of parts) {
    if (cur && typeof cur === 'object' && p in cur) {
      cur = cur[p];
    } else {
      return key;
    }
  }
  return cur;
}

/**
 * Traduce con interpolación posicional: ti('pricing.annualBilling', 'es', [228])
 */
export function ti(key: string, lang: Lang | undefined, args: (string | number)[]): string {
  const raw = t(key, lang);
  if (typeof raw !== 'string') return key;
  return raw.replace(/\{(\d+)\}/g, (_, i) => String(args[Number(i)] ?? ''));
}
